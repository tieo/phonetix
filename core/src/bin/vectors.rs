//! The cases that pin every port to what the core answers.
//!
//! The sprinkle rule lives in the core, and the Android overlay carries a port of it that
//! cannot import Rust. So this writes what the rule answers for a spread of inputs, and the
//! port asserts itself against the file. A rule changed here and not carried across fails that
//! test, rather than one setting quietly meaning two different things on two devices.
//!
//!   cargo run -p lexcore --bin vectors
//!
//! The JSON is written by hand, in the same shape and order the file already has, so that
//! regenerating it after a change shows the change and nothing else.

use std::fs;
use std::path::Path;

use lexcore::sprinkle::{density_for_pos, picks, pos_for_density, DENSITY_MAX, DENSITY_MIN};

/// A spread of shapes rather than a word list: lengths on both sides of every bend in the
/// rarity boost, repeats to exercise the occurrence gate, and words outside ASCII to catch a
/// hash that went through bytes instead of code units.
const WORDS: [&str; 17] = [
    "a",
    "to",
    "cat",
    "four",
    "seven",
    "letter",
    "reading",
    "language",
    "pronounce",
    "dictionary",
    "pronunciation",
    "internationalisation",
    "für",
    "größer",
    "naïve",
    "don't",
    "ʃwa",
];
const OCCURRENCES: [u32; 5] = [0, 1, 2, 3, 7];
const DENSITIES: [u32; 8] = [DENSITY_MIN, 3, 5, 8, 12, 20, 33, DENSITY_MAX];

/// A number the way JavaScript writes one, since the file is read by both worlds and 0.5 must
/// not become 0.50000000000000001 in one of them.
fn number(value: f64) -> String {
    if value == value.trunc() {
        return format!("{}", value as i64);
    }
    let mut text = format!("{value}");
    if text.contains('e') {
        text = format!("{value:.17}");
    }
    text
}

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let out = root.join("shared/sprinkle-vectors.json");

    let mut text = String::from("{\n");
    text.push_str(
        "  \"note\": \"Generated by cargo run -p lexcore --bin vectors from \
core/src/sprinkle.rs. Do not edit.\",\n",
    );
    text.push_str(&format!("  \"densityMin\": {DENSITY_MIN},\n"));
    text.push_str(&format!("  \"densityMax\": {DENSITY_MAX},\n"));

    text.push_str("  \"picks\": [\n");
    let mut rows = Vec::new();
    for word in WORDS {
        for occurrence in OCCURRENCES {
            for density in DENSITIES {
                rows.push(format!(
                    "    {{\n      \"word\": \"{}\",\n      \"occurrence\": {},\n      \
\"density\": {},\n      \"picked\": {}\n    }}",
                    word.replace('\\', "\\\\").replace('"', "\\\""),
                    occurrence,
                    density,
                    picks(word, occurrence, density)
                ));
            }
        }
    }
    let picks_count = rows.len();
    text.push_str(&rows.join(",\n"));
    text.push_str("\n  ],\n");

    text.push_str("  \"curve\": [\n");
    let mut rows = Vec::new();
    for step in 0..=100u32 {
        let position = step as f64 / 100.0;
        rows.push(format!(
            "    {{\n      \"pos\": {},\n      \"density\": {}\n    }}",
            number(position),
            density_for_pos(position)
        ));
    }
    let curve_count = rows.len();
    text.push_str(&rows.join(",\n"));
    text.push_str("\n  ],\n");

    text.push_str("  \"inverse\": [\n");
    let mut rows = Vec::new();
    for density in DENSITY_MIN..=DENSITY_MAX {
        rows.push(format!(
            "    {{\n      \"density\": {},\n      \"pos\": {}\n    }}",
            density,
            number(pos_for_density(density, 100))
        ));
    }
    let inverse_count = rows.len();
    text.push_str(&rows.join(",\n"));
    text.push_str("\n  ]\n}\n");

    fs::write(&out, text).expect("could not write the vectors");
    println!(
        "wrote {}: {picks_count} pick cases, {curve_count} curve, {inverse_count} inverse",
        out.display()
    );
}
